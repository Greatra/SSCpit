for (const [qid, rubric] of Object.entries(rubricDatabase)) {
  // Regex to find the question object by id and inject prastavana & nishkarsha if not already present
  const qPattern = new RegExp(`(id:\\s*['"]${qid}['"][\\s\\S]*?answerMarathiDetailed:\\s*['"][\\s\\S]*?['"],)`);
  if (qPattern.test(newContent)) {
    // Check if prastavana is already there
    const hasPrastavana = new RegExp(`id:\\s*['"]${qid}['"][\\s\\S]*?prastavana:`).test(newContent);
    if (!hasPrastavana) {
      newContent = newContent.replace(qPattern, `$1\n        prastavana: '${rubric.prastavana}',\n        nishkarsha: '${rubric.nishkarsha}',`);
      updatedCount++;
    }
  }
}

